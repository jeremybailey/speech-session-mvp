import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {factSchema,incrementalVersion} from '../api/_lib/incremental-contract';
const properties={...(factSchema as any).properties,occurrenceID:{type:'string'},sourceHash:{type:'string'},recordID:{type:'string'},unitKey:{type:'string'},start:{type:'integer'}};
function swift(schema:any):string {
 if(schema.anyOf)return swift(schema.anyOf.find((v:any)=>v.type!=='null'))+'?';
 if(schema.type==='string')return 'String';if(schema.type==='integer')return 'Int';
 if(schema.type==='array')return schema.items.type==='object'?(schema.items.properties.system?'[ConditionSystem]':'[Field]'):'['+swift(schema.items)+']';
 throw Error('unsupported_wire_type');
}
const code=`// Generated by scripts/generate-incremental-types.ts; contract ${incrementalVersion}.
import Foundation

public struct IncrementalRecordFact: Codable, Sendable {
    public struct ConditionSystem: Codable, Sendable { public let name: String; public let system: String }
    public struct Field: Codable, Sendable { public let key: String; public let value: String }
${Object.entries(properties).map(([key,value])=>'    public let '+key+': '+swift(value)).join('\n')}
}
`;
const target=resolve('../Sources/SpeechSessionPersistence/GeneratedIncrementalFact.swift');
if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==code)throw Error('generated_contract_drift');}
else writeFileSync(target,code);
